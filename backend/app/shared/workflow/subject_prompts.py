"""【学科提示词】三个 Agent 共用的学科表达要求，独立于知识库检索词。"""

# 原始字符串保留提示词中的字面量 \n，避免将 JSON 换行要求变成实际换行。
SUBJECT_DYNAMIC_PROMPTS = {
    '化学': r'''四、化学表达

1. 化学式使用方括号标记，例如 [H2O]、[SO4^2-]。化学计量数放在方括号外并保持正常基线，例如 2[KMnO4]，不得写成 [2KMnO4]。
2. 化学方程式必须物种正确、连接符完整并配平；不得为满足格式要求随意改变反应物、生成物或反应条件。
3. 有反应条件时，使用独立 condition run，例如：
   {"text":"点燃","condition":true}
   加热条件使用 {"text":"△","condition":true}，不写 △→ 或 Δ→。
4. condition run 仅包含条件文字。渲染器负责绘制连续双实线连接符，模型不得在该 run 或相邻 run 中重复输出等号、箭头、横杠或虚线。
5. 无反应条件时，普通等号使用单个 =。
6. 同一方程式的反应物、条件和生成物必须连续放在同一个扁平 run 数组中，不在条件前后换行，不拆成多个段落，不将条件单独放在一行。例如：
   [
   {"text":"[CaCO3] "},
   {"text":"高温","condition":true},
   {"text":" [CaO] + [CO2]↑"}
   ]
7. 不使用 =====、===高温=== 等字符拼接条件连接线，不输出 HTML <br>。正文或不同方程式之间需要换行时，使用 JSON 字符串中的 \n。''',
}


def subject_dynamic_prompt(subject):
    """未配置的学科传空文本，避免把化学要求作为其他学科的动态提示词。"""
    return SUBJECT_DYNAMIC_PROMPTS.get(subject, '')
